# ---------------------------------------------------------------------------------------------------------------
# Sources and digests. ONE definition, consumed by the runner AND the checker's report verification.
# ---------------------------------------------------------------------------------------------------------------

def source_files(spec: dict) -> list[Path]:
    """The files a lane's digest is taken over: every source file under its trees, plus any named file.

    *Kept as a LIST OF PATHS so a caller can audit exactly which bytes the digest bound -- a digest alone is not
    evidence about WHICH sources it covered.* **RESOLVED FROM `REPO`, so a foreign cwd cannot change the answer.**
    """
    out: list[Path] = []
    for rel in spec.get("sources", ()):
        base = REPO / rel
        if base.is_file():
            out.append(base)
        elif base.is_dir():
            out.extend(sorted(p for p in base.rglob("*") if p.suffix in (".kt", ".kts", ".swift", ".py")))
    return sorted(set(out))


def source_digest(spec: dict) -> str:
    """The digest over a lane's sources, keyed by REPOSITORY-RELATIVE path so it is stable across checkouts."""
    h = hashlib.sha256()
    for path in source_files(spec):
        try:
            rel = str(path.relative_to(REPO))
        except ValueError:
            rel = str(path)
        h.update(rel.encode())
        h.update(b"\0")
        h.update(path.read_bytes())
        h.update(b"\0")
    return h.hexdigest()


def _sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


# ---------------------------------------------------------------------------------------------------------------
# JUnit reading: the counts and the class population a report must reconcile against, read from the REAL XML.
# ---------------------------------------------------------------------------------------------------------------

def junit_totals(results_dir: Path) -> dict:
    """Parse every JUnit XML under `results_dir` and return the aggregate counts.

    *`tests=0` across a non-empty file set is the shape a broken build, a wrong filter or a truncated mirror all
    produce -- so the counts are returned verbatim and the CHECKER refuseth zero rather than this reader guessing.*
    """
    total = {"files": 0, "tests": 0, "failures": 0, "errors": 0, "skipped": 0}
    if not results_dir.is_dir():
        return total
    for path in sorted(results_dir.glob("*.xml")):
        if path.stat().st_size == 0:
            continue
        total["files"] += 1
        head = path.read_text(encoding="utf-8", errors="replace")[:4000]
        for key in ("tests", "failures", "errors", "skipped"):
            m = re.search(rf'(?<![\w-]){key}="(\d+)"', head)
            total[key] += int(m.group(1)) if m else 0
    return total


def junit_classes(results_dir: Path) -> dict[str, int]:
    """`{classname: verdicts}` for every `classname="..."` in the lane's real XML (last segment of an FQCN)."""
    seen: dict[str, int] = {}
    if not results_dir.is_dir():
        return seen
    for path in sorted(results_dir.glob("*.xml")):
        text = path.read_text(encoding="utf-8", errors="replace")
        for m in re.finditer(r'(?<![\w-])classname="([^"]+)"', text):
            cls = m.group(1).split(".")[-1]
            seen[cls] = seen.get(cls, 0) + 1
    return seen


# ---------------------------------------------------------------------------------------------------------------
# The runner: the REAL target, the child's OWN status, the evidence the lane emits.
